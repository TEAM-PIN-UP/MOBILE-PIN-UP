package com.pinup.placePinup.util

/**
 * 지도 줌 레벨 정책.
 *
 * 네이버 지도 스케일바(80dp 기준)의 축척과 줌 레벨 대응은 아래와 같다.
 * 줌 15 = 축척 200m, 줌 16 = 축척 100m, 줌 17 = 축척 50m.
 */
object MapZoom {
    /**
     * 클러스터링을 수행할 최대 줌 레벨.
     * 이 값보다 크게 확대하면(= 줌 16, 축척 100m부터) 모든 핀이 클러스터링 없이 개별로 노출된다.
     */
    const val MAX_CLUSTERING = 15

    /**
     * 특정 장소를 지도에 노출할 때 보장할 최소 줌 레벨.
     * 클러스터링이 풀리는 축척(100m)이므로 해당 장소가 반드시 개별 핀으로 보인다.
     * 이미 더 확대된 상태라면 현재 줌을 유지한다.
     */
    const val PLACE_FOCUS = 16.0
}
